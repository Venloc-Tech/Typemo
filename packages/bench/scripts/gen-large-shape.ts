/*
 * Generates src/data/shapes/large-doc.generated.ts: the ~200-field entity of the large shape.
 *
 * Usage: bun run packages/bench/scripts/gen-large-shape.ts (output is committed; rerun only when the shape changes).
 */
/** Number of string fields. */
const STRINGS = 120;
/** Number of number fields. */
const NUMBERS = 60;
/** Number of fields of the nested meta object. */
const META = 10;

/**
 * Zero-pads a field number to three digits.
 *
 * @param n - The number.
 * @returns For example `007`.
 */
const pad = (n: number): string => String(n).padStart(3, "0");
const lines: string[] = [
  "// GENERATED by packages/bench/scripts/gen-large-shape.ts — do not edit by hand.",
  'import { Entity, Prop, Schema } from "@venloc/typemo";',
  "",
  `export const LARGE_STRINGS = ${STRINGS};`,
  `export const LARGE_NUMBERS = ${NUMBERS};`,
  `export const LARGE_META = ${META};`,
  "",
  "@Schema()",
  "export class LargeItem {",
  "  @Prop(() => String, { required: true }) sku!: string;",
  "  @Prop(() => Number, { required: true, min: 0 }) qty!: number;",
  "  @Prop(() => Number, { required: true, min: 0 }) price!: number;",
  "  @Prop(() => String) note?: string;",
  "  @Prop(() => [String]) tags!: string[];",
  "}",
  "",
  "@Schema({ nested: true })",
  "export class LargeMeta {",
];
for (let i = 0; i < META; i++) lines.push(`  @Prop(() => String) m${i}?: string;`);
lines.push("}", "", '@Schema({ collection: "bench_large" })', "export class LargeDoc extends Entity {");
for (let i = 0; i < STRINGS; i++)
  lines.push(
    `  @Prop(() => String${i === 0 ? ", { required: true, index: true }" : ""}) s${pad(i)}${i === 0 ? "!" : "?"}: string;`,
  );
for (let i = 0; i < NUMBERS; i++) lines.push(`  @Prop(() => Number) n${pad(i)}?: number;`);
lines.push("  @Prop(() => LargeMeta) meta?: LargeMeta;", "  @Prop(() => [LargeItem]) items!: LargeItem[];", "}", "");
await Bun.write(new URL("../src/data/shapes/large-doc.generated.ts", import.meta.url), lines.join("\n"));
console.log("large-doc.generated.ts written");
